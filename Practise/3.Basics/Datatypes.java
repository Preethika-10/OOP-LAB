public class Datatypes {
       public static void main(String[] args){
             int num = 100;
             System.out.println("The number is "+num);
             byte sqr = 81;
             System.out.println("What is the square of 9? "+sqr);
             float pi = 3.14f;
             System.out.println("The value of pi is "+pi);
             double gr = 1.61803d;
             System.out.println("The Golden ratio is "+gr);
             short days = 365;
             System.out.println("The number of days in a standard,non-leap year is "+days);
             long min = 525600L;
             System.out.println("No.of minutes in a year is "+min);
             char grade = 'O';
             System.out.println("The top grade is "+grade);
             boolean value = true;
             System.out.println("Is the number 1 neither prime nor composite? "+value);
       }
}
